def header_section(doc: MarkdownDoc, ctx: Context, extra: Optional[List[Tuple[str, Any]]] = None) -> None:
    item = ctx.item
    doc.heading(1, "{}: {}".format(item.kind.label, os.path.basename(item.path)))
    doc.para(KIND_DESCRIPTIONS.get(item.kind.key, ""))
    try:
        mtime = _dt.datetime.fromtimestamp(os.path.getmtime(item.path)).strftime("%Y-%m-%d %H:%M:%S")
    except (OSError, OverflowError, ValueError):
        mtime = ""
    companions = ", ".join(os.path.basename(p) for p in item.companions.values())
    pairs: List[Tuple[str, Any]] = [
        ("Source file", item.relpath.replace("\\", "/")),
        ("File type", "{} ({})".format(item.kind.label, item.ext)),
        ("Size", human_size(item.size)),
        ("Last modified", mtime),
        ("Companion files", companions),
    ]
    if extra:
        pairs.extend(extra)
    doc.kv(pairs)


def warnings_section(doc: MarkdownDoc, ctx: Context) -> None:
    if ctx.warnings:
        doc.heading(2, "Conversion notes")
        doc.bullets(ctx.warnings)
    doc.raw("---\n*Generated by vfp2md {}.*".format(__version__))


