_PROC_RE = re.compile(r"^[ \t]*(?:PROTECTED\s+|HIDDEN\s+)?(?:PROCEDURE|PROC|FUNCTION|FUNC)\s+([^\s(]+)", re.IGNORECASE)
_END_RE = re.compile(r"^[ \t]*(?:ENDPROC|ENDFUNC)\b", re.IGNORECASE)


def split_procedures(code: str) -> Tuple[str, List[Tuple[str, str]]]:
    """Split method code into ``(preamble, [(name, full_text), ...])``.

    Tolerates missing ENDPROC (a new PROCEDURE closes the previous one).
    """
    code = clean_text(code)
    preamble: List[str] = []
    procs: List[Tuple[str, str]] = []
    name: Optional[str] = None
    body: List[str] = []
    for line in code.split("\n"):
        m = _PROC_RE.match(line)
        if m:
            if name is not None:
                procs.append((name, "\n".join(body).rstrip()))
            name, body = m.group(1), [line]
            continue
        if name is not None:
            body.append(line)
            if _END_RE.match(line):
                procs.append((name, "\n".join(body).rstrip()))
                name, body = None, []
        else:
            preamble.append(line)
    if name is not None:
        procs.append((name, "\n".join(body).rstrip()))
    return "\n".join(preamble).strip(), procs


def parse_properties(text: str) -> List[Tuple[str, str]]:
    """Parse a PROPERTIES memo (``Name = Value`` lines) into ordered pairs.

    Lines that do not look like assignments are treated as continuations
    of the previous value, which is how multi line values appear.
    """
    pairs: List[Tuple[str, str]] = []
    for line in clean_text(text).split("\n"):
        if not line.strip():
            continue
        name, sep, value = line.partition(" = ")
        if sep and name.strip() and " " not in name.strip() and len(name.strip()) < 128:
            pairs.append((name.strip(), value))
        elif pairs:
            k, v = pairs[-1]
            pairs[-1] = (k, v + "\n" + line)
        else:
            pairs.append(("(unparsed)", line))
    return pairs


def generic_records(doc: MarkdownDoc, table: DbfTable, ctx: Context, title_fields: Tuple[str, ...] = ()) -> int:
    """Fallback renderer: dump every record, code-like memos as code blocks."""
    count = 0
    for rec in table.records(include_deleted=ctx.options.include_deleted):
        count += 1
        title = ""
        for name in title_fields:
            title = rec.text(name).strip()
            if title:
                break
        doc.heading(3, "Record {}{}".format(rec.index, ": " + title if title else ""))
        short: List[Tuple[str, Any]] = []
        long_values: List[Tuple[str, str]] = []
        for f in table.visible_fields:
            value = rec.values.get(f.name)
            if isinstance(value, (bytes, bytearray)):
                if value:
                    short.append((f.name, "<binary, {} bytes>".format(len(value))))
                continue
            if isinstance(value, str) and ("\n" in value or "\r" in value or len(value) > 120):
                long_values.append((f.name, value))
            elif value not in (None, "") and value is not False:
                short.append((f.name, value))
        doc.kv(short)
        for name, value in long_values:
            doc.para("**{}:**".format(name))
            doc.code(value, "foxpro")
        for err in rec.errors:
            ctx.warn("record {}: {}".format(rec.index, err))
    return count
