class Options:
    """User tunable conversion settings."""

    def __init__(
        self,
        encoding: Optional[str] = None,
        max_rows: int = 100,
        max_cell: int = 300,
        include_deleted: bool = False,
    ):
        self.encoding = encoding  # None = use the table's code page mark
        self.max_rows = max_rows  # 0 = every row
        self.max_cell = max_cell  # 0 = never truncate table cells
        self.include_deleted = include_deleted


class Context:
    """Per file state handed to a converter."""

    def __init__(self, item: DiscoveredFile, options: Options):
        self.item = item
        self.options = options
        self.warnings: List[str] = []

    def warn(self, message: str) -> None:
        if message not in self.warnings:
            self.warnings.append(message)

    def open_table(self, memo_ext: Optional[str] = None) -> DbfTable:
        memo_path = None
        if memo_ext and memo_ext in self.item.companions:
            memo_path = self.item.companions[memo_ext]
        return DbfTable(self.item.path, encoding=self.options.encoding, memo_ext=memo_ext, memo_path=memo_path)

    def collect_table_warnings(self, table: DbfTable) -> None:
        for w in table.warnings:
            self.warn(w)
        if table.memo is not None:
            for w in table.memo.warnings:
                self.warn(w)


